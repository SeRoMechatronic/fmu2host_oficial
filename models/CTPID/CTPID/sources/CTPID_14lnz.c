const char *CTPID_linear_model_frame()
{
  return "model linearized_model \"CTPID\"\n"
  "  parameter Integer n = 1 \"number of states\";\n"
  "  parameter Integer m = 2 \"number of inputs\";\n"
  "  parameter Integer p = 4 \"number of outputs\";\n"
  "\n"
  "  parameter Real x0[n] = %s;\n"
  "  parameter Real u0[m] = %s;\n"
  "\n"
  "  parameter Real A[n, n] =\n\t[%s];\n\n"
  "  parameter Real B[n, m] =\n\t[%s];\n\n"
  "  parameter Real C[p, n] =\n\t[%s];\n\n"
  "  parameter Real D[p, m] =\n\t[%s];\n\n"
  "\n"
  "  Real x[n](start=x0);\n"
  "  input Real u[m](start=u0);\n"
  "  output Real y[p];\n"
  "\n"
  "  Real 'x_integrador' = x[1];\n"
  "  Real 'u_consigna' = u[1];\n"
  "  Real 'u_temperatura' = u[2];\n"
  "  Real 'y_ledAlcanzado' = y[1];\n"
  "  Real 'y_ledPorDebajo' = y[2];\n"
  "  Real 'y_ledPorEncima' = y[3];\n"
  "  Real 'y_ventilador' = y[4];\n"
  "equation\n"
  "  der(x) = A * x + B * u;\n"
  "  y = C * x + D * u;\n"
  "end linearized_model;\n";
}
